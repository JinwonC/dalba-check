export function translate(lang: Lang, en: string, vars?: Record<string, string | number>): string {
  let s = lang === "ko" ? (KO[en] ?? en) : en;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export type T = (en: string, vars?: Record<string, string | number>) => string;

const MON = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];

/** Calendar date ("2026-12-18" or an ISO timestamp) in the reader's language. */
export function fmtDate(lang: Lang, iso: string | null | undefined): string {
  const m = /^(\d{4})-(\d{2})-(\d{2})/.exec(iso || "");
  if (!m) return "";
  return lang === "ko" ? `${m[1]}.${m[2]}.${m[3]}` : `${MON[Number(m[2]) - 1]} ${Number(m[3])}, ${m[1]}`;
}

/** Timestamp with time, shown in Korea time for Korean and UTC for English. */
export function fmtWhen(lang: Lang, iso: string | null | undefined): string {
  if (!iso) return "";
  const d = new Date(iso);
  if (isNaN(d.getTime())) return "";
  if (lang === "ko") {
    const k = new Date(d.getTime() + 9 * 3600000).toISOString();
    return `${k.slice(0, 10).replace(/-/g, ".")} ${k.slice(11, 16)}`;
  }
  return d.toLocaleString("en-US", { month: "short", day: "numeric", year: "numeric", hour: "2-digit", minute: "2-digit", timeZone: "UTC" }) + " UTC";
}
